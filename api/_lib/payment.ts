// Payment gateway adapters. PAYMENT_PROVIDER = mock | doku | midtrans | xendit.
// mock     : simulated payment page, no subscription required. Refuses to run on production.
// doku     : production-grade — active the moment DOKU_CLIENT_ID + DOKU_SECRET_KEY are set.
// midtrans / xendit : ready, switch on once the merchant account is approved and keys are in env.
import { createHash, timingSafeEqual } from 'node:crypto';
import { RpcError } from './db.js';
import { checkStatus as dokuCheckStatus, createCheckout, verifyNotification } from './doku.js';

export interface PaymentCreateInput {
  kode: string;
  invoice: string;         // pre-generated by payment_next_invoice, unique per attempt
  total: number;
  itemName: string;
  nama: string;
  email?: string | null;
  wa: string;
  expiresAt: string;       // ISO; gateway expiry is aligned with our stock hold
  finishUrl: string;       // where the guest lands after paying
  baseUrl: string;
}
export interface PaymentCreateResult {
  provider: string;
  invoice: string;
  payUrl: string;
  requestId?: string;
  tokenId?: string;
}

// DOKU's own vocabulary; other gateways map their statuses onto it so the DB layer only knows one set.
export type PaymentStatus = 'SUCCESS' | 'FAILED' | 'PENDING' | 'EXPIRED' | 'REFUNDED' | 'TIMEOUT' | 'REDIRECT';
export interface PaymentEvent {
  invoice: string;
  status: PaymentStatus;
  amount: number | null;
  raw: unknown;
}

export interface PaymentProvider {
  name: string;
  create(p: PaymentCreateInput): Promise<PaymentCreateResult>;
  // rawBody = exact bytes received (needed for signature-verifying gateways); target = path of OUR
  // notification endpoint. Returns null when the signature/token is invalid (caller responds 401).
  parseWebhook(rawBody: string, headers: Record<string, string | string[] | undefined>, target: string): PaymentEvent | null;
  // Active status pull. Only gateways with a real status endpoint (DOKU) implement this.
  checkStatus?(invoice: string): Promise<PaymentEvent>;
}

const minutesLeft = (iso: string) => Math.max(1, Math.floor((new Date(iso).getTime() - Date.now()) / 60000));
const safeEqual = (a: string, b: string) => {
  const x = Buffer.from(a), y = Buffer.from(b);
  return x.length === y.length && timingSafeEqual(new Uint8Array(x), new Uint8Array(y));
};
const headerStr = (h: string | string[] | undefined): string => (Array.isArray(h) ? h[0] ?? '' : h ?? '');
const need = (name: string) => {
  const v = process.env[name];
  if (!v) throw new RpcError('CONFIG', 500, `${name} belum di-set`);
  return v;
};

const mock: PaymentProvider = {
  name: 'mock',
  async create(p) {
    if (process.env.VERCEL_ENV === 'production') throw new RpcError('PEMBAYARAN_BELUM_AKTIF', 503);
    return { provider: 'mock', invoice: p.invoice, payUrl: `${p.baseUrl}/api/payment/mock?kode=${encodeURIComponent(p.kode)}` };
  },
  parseWebhook: () => null, // mock settles through /api/payment/mock, never through the webhook
};

const doku: PaymentProvider = {
  name: 'doku',
  async create(p) {
    const methods = (process.env.DOKU_PAYMENT_METHODS || '').split(',').map(s => s.trim()).filter(Boolean);
    const result = await createCheckout({
      invoice: p.invoice,
      amount: Math.round(p.total),
      paymentDueMinutes: minutesLeft(p.expiresAt),
      customerId: p.kode,
      customerName: p.nama,
      customerEmail: p.email,
      customerPhone: p.wa,
      callbackUrl: p.finishUrl,
      callbackUrlResult: p.finishUrl,
      overrideNotificationUrl: `${p.baseUrl}/api/payment/webhook`,
      paymentMethodTypes: methods.length ? methods : undefined,
    });
    return { provider: 'doku', invoice: result.invoice, payUrl: result.payUrl, requestId: result.requestId, tokenId: result.tokenId };
  },
  parseWebhook(rawBody, headers, target) {
    if (!verifyNotification(rawBody, headers, target)) return null;
    let data: any;
    try { data = JSON.parse(rawBody); } catch { return null; }
    const invoice = String(data?.order?.invoice_number || '');
    const status = String(data?.transaction?.status || '').toUpperCase() as PaymentStatus;
    if (!invoice || !status) return null;
    const amount = data?.order?.amount != null ? Math.round(Number(data.order.amount)) : null;
    return { invoice, status, amount, raw: data };
  },
  async checkStatus(invoice) {
    const r = await dokuCheckStatus(invoice);
    return { invoice, status: r.status as PaymentStatus, amount: r.amount, raw: r.raw };
  },
};

const midtrans: PaymentProvider = {
  name: 'midtrans',
  async create(p) {
    const key = need('MIDTRANS_SERVER_KEY');
    const host = process.env.MIDTRANS_IS_PRODUCTION === 'true' ? 'https://app.midtrans.com' : 'https://app.sandbox.midtrans.com';
    const res = await fetch(`${host}/snap/v1/transactions`, {
      method: 'POST',
      headers: {
        Accept: 'application/json', 'Content-Type': 'application/json',
        Authorization: 'Basic ' + Buffer.from(`${key}:`).toString('base64'),
        'X-Override-Notification': `${p.baseUrl}/api/payment/webhook`,
      },
      body: JSON.stringify({
        transaction_details: { order_id: p.invoice, gross_amount: p.total },
        item_details: [{ id: p.kode, price: p.total, quantity: 1, name: p.itemName.slice(0, 50) }],
        customer_details: { first_name: p.nama, email: p.email || undefined, phone: p.wa },
        expiry: { unit: 'minutes', duration: minutesLeft(p.expiresAt) },
        callbacks: { finish: p.finishUrl },
      }),
    });
    const data: any = await res.json().catch(() => ({}));
    if (!res.ok || !data.redirect_url) {
      console.error('[midtrans] create failed', res.status, data);
      throw new RpcError('GATEWAY_ERROR', 502);
    }
    return { provider: 'midtrans', invoice: p.invoice, payUrl: data.redirect_url };
  },
  parseWebhook(rawBody) {
    let b: any;
    try { b = JSON.parse(rawBody); } catch { return null; }
    const key = process.env.MIDTRANS_SERVER_KEY || '';
    const expected = createHash('sha512').update(`${b.order_id}${b.status_code}${b.gross_amount}${key}`).digest('hex');
    if (!key || typeof b.signature_key !== 'string' || !safeEqual(expected, b.signature_key)) return null;
    const s = b.transaction_status;
    const paid = b.status_code === '200' && (s === 'settlement' || (s === 'capture' && (!b.fraud_status || b.fraud_status === 'accept')));
    const status: PaymentStatus = paid ? 'SUCCESS'
      : s === 'expire' ? 'EXPIRED'
      : (s === 'cancel' || s === 'deny') ? 'FAILED'
      : s === 'refund' ? 'REFUNDED'
      : 'PENDING';
    return { invoice: String(b.order_id), status, amount: Math.round(Number(b.gross_amount)), raw: b };
  },
};

const xendit: PaymentProvider = {
  name: 'xendit',
  async create(p) {
    const key = need('XENDIT_SECRET_KEY');
    const res = await fetch('https://api.xendit.co/v2/invoices', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Authorization: 'Basic ' + Buffer.from(`${key}:`).toString('base64') },
      body: JSON.stringify({
        external_id: p.invoice,
        amount: p.total,
        currency: 'IDR',
        description: `${p.itemName} (${p.kode})`,
        payer_email: p.email || undefined,
        customer: { given_names: p.nama, mobile_number: p.wa },
        invoice_duration: minutesLeft(p.expiresAt) * 60,
        success_redirect_url: p.finishUrl,
        failure_redirect_url: p.finishUrl,
      }),
    });
    const data: any = await res.json().catch(() => ({}));
    if (!res.ok || !data.invoice_url) {
      console.error('[xendit] create failed', res.status, data);
      throw new RpcError('GATEWAY_ERROR', 502);
    }
    return { provider: 'xendit', invoice: p.invoice, payUrl: data.invoice_url };
  },
  parseWebhook(rawBody, headers) {
    const token = process.env.XENDIT_CALLBACK_TOKEN || '';
    const got = headerStr(headers['x-callback-token']);
    if (!token || !safeEqual(token, got)) return null;
    let b: any;
    try { b = JSON.parse(rawBody); } catch { return null; }
    // Xendit sends further statuses (e.g. STOPPED); anything not explicitly recognized stays PENDING
    // rather than being guessed at, so reconcile / a later webhook can resolve it correctly.
    const status: PaymentStatus = (b.status === 'PAID' || b.status === 'SETTLED') ? 'SUCCESS'
      : b.status === 'EXPIRED' ? 'EXPIRED'
      : 'PENDING';
    return { invoice: String(b.external_id), status, amount: b.paid_amount ?? b.amount ?? null, raw: b };
  },
};

const PROVIDERS: Record<string, PaymentProvider> = { mock, doku, midtrans, xendit };

export function provider(): PaymentProvider {
  const name = process.env.PAYMENT_PROVIDER;
  if (!name) {
    return process.env.DOKU_CLIENT_ID && process.env.DOKU_SECRET_KEY ? doku : mock;
  }
  const p = PROVIDERS[name];
  if (!p) throw new RpcError('CONFIG', 500, `PAYMENT_PROVIDER tidak dikenal: ${name}`);
  return p;
}
